"""Offline package audit. No SQL connection, build, native or perf execution."""
import ast
from datetime import datetime, timezone
import difflib
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def main():
    manifest = json.loads((HERE / "manifest.json").read_text(encoding="utf-8"))
    source = Path(manifest["source_root"])
    checked = []
    for record in manifest["source_files"] + manifest["context_only_files"]:
        original = (HERE / record["snapshot"]).read_bytes()
        assert sha(original) == record["original_content_sha256"], record["path"]
        assert (source / record["path"]).read_bytes() == original, record["path"]
        checked.append(record["path"])
    for record in manifest["source_files"]:
        assert sha((HERE / record["path"]).read_bytes()) == record["new_sha256"], record["path"]
    for path in HERE.rglob("*.py"):
        ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    test_path = HERE / "unittest/storage/fts/test_query_materialization.py"
    namespace = {"__name__": "round11_static_only", "__file__": str(test_path)}
    # Evaluate definitions only. Main/capture/run_query are never called; the
    # module imports only Python standard-library modules at definition time.
    exec(compile(test_path.read_text(encoding="utf-8"), str(test_path), "exec"), namespace)
    cases = list(namespace["cases"]())
    identifiers = [case["id"] for case in cases]
    assert len(set(identifiers)) == len(identifiers)
    for case in cases:
        assert case["sql"].count("%s") == len(case["params"]), case["id"]
    assert all(any("/" + mode + "/" in case["id"] for case in cases)
               for mode in ("default", "batch1", "batch256", "batch513"))
    assert all(any(parser + "/" + table + "/" in case["id"] for case in cases)
               for parser in ("beng", "ik")
               for table in ("unsigned_docs", "signed_docs", "binary_docs", "composite_docs"))
    fixture = test_path.with_name("query_materialization_expected.json.gz")
    assert not fixture.exists(), "A fixture must not be generated by staging"
    regression = "diff --git a/" + test_path.relative_to(HERE).as_posix() + " b/" + test_path.relative_to(HERE).as_posix() + "\nnew file mode 100644\n"
    regression += "".join(difflib.unified_diff([], test_path.read_text(encoding="utf-8").splitlines(True),
                                             fromfile="/dev/null", tofile="b/" + test_path.relative_to(HERE).as_posix()))
    (HERE / "regression.patch").write_text(regression, encoding="utf-8", newline="\n")
    (HERE / "proposal.patch").write_text((HERE / "source.patch").read_text(encoding="utf-8") + regression,
                                        encoding="utf-8", newline="\n")
    audit = {"created_utc": datetime.now(timezone.utc).isoformat(),
             "source_files_unchanged": checked, "python_ast": "passed",
             "case_ids_unique": True, "sql_placeholder_arity": "passed",
             "cases": len(cases), "documents_per_table": len(namespace["documents"]()),
             "tables": 8, "requested_execution_modes": 4,
             "workload_sha256": namespace["workload_hash"](cases),
             "fixture_generated": False, "sql_executed": False, "native_executed": False,
             "build_executed": False, "perf_executed": False,
             "limits": "Offline checks do not validate SQL syntax/support or effective optimizer plans."}
    (HERE / "static-audit.json").write_text(json.dumps(audit, indent=2) + "\n", encoding="utf-8")
    manifest["new_test_files"] = [{"path": test_path.relative_to(HERE).as_posix(),
                                  "original_exists": False, "new_sha256": sha(test_path.read_bytes())}]
    manifest["validation"] = audit
    manifest["artifacts"] = [{"path": path.relative_to(HERE).as_posix(),
                              "sha256": sha(path.read_bytes()), "bytes": path.stat().st_size}
                             for path in sorted(HERE.rglob("*"))
                             if path.is_file() and path.name != "manifest.json"]
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print("STATIC AUDIT:", len(cases), "cases;", len(checked), "source/context hashes unchanged; no SQL/build/native/perf")


if __name__ == "__main__":
    main()
